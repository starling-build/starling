    /// Pattern pixels a picture pixel spans: drawn eight times over, so
    /// that a viewer smoothing the picture blurs only the edges.
    static let magnify = 8
    /// Repeats of the 8×8 pattern in one tile, across and down.
    static let repeats = 4

    /// The fill: the picture, tiled one pattern pixel a point, and the two
    /// colours' blend by share as the colour that stands for it.
    static func fill(preset: String, foreground: Color, background: Color) -> SlideFill {
        let bits = rows[preset] ?? rows["pct50"]!
        let on = bits.reduce(0) { $0 + $1.nonzeroBitCount }
        let share = Double(on) / 64
        func mix(_ sh: Int) -> Int {
            let f = Double((foreground.value >> sh) & 0xFF), b = Double((background.value >> sh) & 0xFF)
            return Int((f * share + b * (1 - share)).rounded())
        }
        var f = SlideFill(color: Color(0xFF00_0000 | Int64(mix(16) << 16 | mix(8) << 8 | mix(0))))
        let side = 8 * repeats * magnify
        let data = bmp(side: side) { x, y in
            let px = (x / magnify) % 8, py = (y / magnify) % 8
            return bits[py] & (1 << px) != 0 ? foreground : background
        }
        let name = "pattern-\(preset)-\(String(foreground.value, radix: 16))-\(String(background.value, radix: 16)).bmp"
        f.image = ImageAttachment(data: data, width: Double(8 * repeats), height: Double(8 * repeats), name: name)
        f.tiled = true
        // A picture's pixel is 0.75 pt at a tile scale of 1.
        f.tileScale = 1 / (0.75 * Double(magnify))
        f.tileScaleY = f.tileScale
        f.tileAnchored = true
        return f
    }

    /// A 24-bit BMP, `side` pixels square, coloured by `color(x, y)` from
    /// the top left.
    static func bmp(side: Int, _ color: (Int, Int) -> Color) -> Data {
        let row = side * 3, pad = (4 - row % 4) % 4
        let size = 54 + (row + pad) * side
        var b = [UInt8]()
        b.reserveCapacity(size)
        func u16(_ v: Int) { b += [UInt8(v & 0xFF), UInt8((v >> 8) & 0xFF)] }
        func u32(_ v: Int) { u16(v & 0xFFFF); u16((v >> 16) & 0xFFFF) }
        b += [0x42, 0x4D]; u32(size); u32(0); u32(54)
        u32(40); u32(side); u32(side); u16(1); u16(24); u32(0); u32(size - 54); u32(2835); u32(2835); u32(0); u32(0)
        for y in stride(from: side - 1, through: 0, by: -1) {
            for x in 0 ..< side {
                let c = color(x, y).value
                b += [UInt8(c & 0xFF), UInt8((c >> 8) & 0xFF), UInt8((c >> 16) & 0xFF)]
            }
            b += [UInt8](repeating: 0, count: pad)
        }
        return Data(b)
    }
