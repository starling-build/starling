                while j < u.count, isMatra(u[j].value) { j += 1 }
            } else {
                j = i + 1
            }
            var key = String.UnicodeScalarView()
            key.append(contentsOf: u[i ..< j])
            if let w = (bold ? boldAdvance : advance)[String(key)] { sum += w; known.append(contentsOf: u[i ..< j]); any = true } else { rest = true }
            i = j
        }
        return any ? (sum, String(known), rest) : nil
    }
