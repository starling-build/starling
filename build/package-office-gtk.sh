#!/usr/bin/env bash
# Build starling-office_<ver>_<arch>.deb — Writer, Sheets and Slides as a
# STANDALONE app for ordinary Linux desktops (GNOME/KDE, Wayland or X11):
# the GTK build of OfficeApp with everything it loads bundled under
# /usr/lib/starling-office. Independent of the desktop package. The same
# tree, relocated, is what build/package-office-flatpak.sh ships.
#
# Prereqs:
#   ninja -C engine/src/out/host_release libflutter_engine.so libflutter_linux_gtk.so
#   STARLING_APP_GTK=1 STARLING_ENGINE_OUT=$PWD/engine/src/out/host_release \
#       swift build -c release --package-path apps/OfficeApp \
#       --scratch-path $PWD/.build-office-gtk
#
#   build/package-office-gtk.sh [outdir]  ->  <outdir>/starling-office_*.deb
#
# The binary needs a glibc at least as new as the build machine's, so the
# .deb installs on this Ubuntu release and newer, not older.
set -euo pipefail

VER="${STARLING_OFFICE_VERSION:-0.1.0}"
PKG=starling-office
OUT="${1:-$HOME/tmp/starling-office-pkg}"
REPO="$(cd "$(dirname "$0")/.." && pwd)"
E="${STARLING_ENGINE_OUT:-$REPO/engine/src/out/host_release}"
[ -f "$E/icudtl.dat" ] || { echo "error: no icudtl.dat in $E" >&2; exit 1; }

B="${STARLING_OFFICE_SCRATCH:-$REPO/.build-office-gtk}"
# <scratch>/release is SwiftPM's symlink into <scratch>/<triple>/release.
REL="$(readlink -f "$B/release")"
BIN="$REL/OfficeApp"

[ -x "$BIN" ] || {
    echo "error: $BIN not built — run the swift build in the header" >&2; exit 1; }
# (grep without -q: -q quits at the first match, readelf dies of SIGPIPE,
# and pipefail reads that as "no match".)
readelf -d "$BIN" | grep flutter_linux_gtk >/dev/null || {
    echo "error: $BIN is not a GTK build — rebuild with STARLING_APP_GTK=1" >&2; exit 1; }
# The stale-scratch trap, refused rather than shipped.
STALE=$(find "$REPO/sdk/Sources" "$REPO/apps/OfficeApp/Sources" \
        -name '*.swift' -newer "$BIN" 2>/dev/null | head -1)
[ -z "$STALE" ] || {
    echo "error: $STALE is newer than $BIN — rebuild before packaging" >&2; exit 1; }

DEB_ARCH="${STARLING_DEB_ARCH:-$(dpkg --print-architecture)}"
ROOT="$OUT/${PKG}_${VER}_${DEB_ARCH}"
LIB=$ROOT/usr/lib/$PKG
rm -rf "$ROOT"
mkdir -p "$LIB/data" "$ROOT/usr/bin" "$ROOT/usr/share/applications" \
         "$ROOT/usr/share/icons/hicolor/scalable/apps" \
         "$ROOT/usr/share/doc/$PKG" "$ROOT/DEBIAN"

# --- payload -----------------------------------------------------------------
install -m755 "$BIN" "$LIB/starling-office"
install -m644 "$REL/libFlutterShared.so" "$LIB/"
install -m644 "$E/libflutter_engine.so" "$E/libflutter_linux_gtk.so" "$LIB/"
install -m644 "$E/icudtl.dat" "$LIB/data/"
for r in "$REL"/*.resources; do
    [ -d "$r" ] && cp -r "$r" "$LIB/"
done
# Swift runtime: the ldd closure, limited to what the swiftly toolchain
# provides (absent on target machines) — same recipe as build/stage.sh.
env -u LD_LIBRARY_PATH ldd "$BIN" 2>/dev/null |
    awk '$3 ~ /swiftly\/toolchains/ {print $3}' | sort -u |
while read -r so; do
    install -m644 "$so" "$LIB/"
done

G="$REPO/build/office-gtk"
install -m755 "$G/starling-office" "$ROOT/usr/bin/starling-office"
for app in writer sheets slides; do
    install -m644 "$G/starling-$app.desktop" "$ROOT/usr/share/applications/"
    install -m644 "$G/starling-$app.svg" "$ROOT/usr/share/icons/hicolor/scalable/apps/"
done

# --- licensing ---------------------------------------------------------------
DOC=$ROOT/usr/share/doc/$PKG
cp "$REPO/LICENSE"     "$DOC/LICENSE.Apache-2.0"
cp "$REPO/sdk/LICENSE" "$DOC/LICENSE.BSD-3-Clause.flutter"
# The fonts and other third-party pieces the app itself bundles.
cp "$REPO/apps/OfficeApp/Sources/OfficeApp/Resources/THIRD_PARTY_NOTICES.md" "$DOC/"
# The engine's own third-party notices, generated by its build.
install -m644 "$REPO/build/flutter_assets/NOTICES.Z" "$DOC/ENGINE-NOTICES.Z"
{
    cat "$REPO/NOTICE"
    cat <<EOT

================================================================================
Full licence texts
================================================================================

Apache-2.0    /usr/share/doc/$PKG/LICENSE.Apache-2.0
BSD-3-Clause  /usr/share/doc/$PKG/LICENSE.BSD-3-Clause.flutter
Bundled fonts /usr/share/doc/$PKG/THIRD_PARTY_NOTICES.md

The Flutter engine's complete third-party notices, generated by its own build:

    /usr/share/doc/$PKG/ENGINE-NOTICES.Z   (gzip; zcat to read)
EOT
} > "$DOC/copyright"

# libxml2.so.2 is bundled on purpose: Swift's FoundationXML asks for that
# name, newer distributions ship only libxml2.so.16, and the toolchain's
# copy (bootstrap.sh's link to the build machine's) needs nothing but zlib.
# No package owns it under that name, hence --ignore-missing-info below.
[ -f "$LIB/libxml2.so.2" ] || { echo "error: no libxml2.so.2 in the Swift runtime closure" >&2; exit 1; }

# --- control -----------------------------------------------------------------
# Depends computed from the bundled ELF objects; -l resolves the private libs
# (Swift runtime, engine, FlutterShared) without generating deps on them.
SCAN="usr/lib/$PKG/starling-office"
for so in "$LIB"/*.so; do SCAN="$SCAN usr/lib/$PKG/$(basename "$so")"; done
SHLIBDEPS_ERR=$OUT/shlibdeps.err
DEPS=$(
    cd "$ROOT" && mkdir -p debian && : > debian/control &&
    dpkg-shlibdeps -O --ignore-missing-info -l"$LIB" $SCAN 2>"$SHLIBDEPS_ERR" |
        sed -n 's/^shlibs:Depends=//p'
    rm -rf "$ROOT/debian"
)
[ -n "$DEPS" ] || {
    echo "ERROR: dpkg-shlibdeps produced no Depends. Install dpkg-dev." >&2
    cat "$SHLIBDEPS_ERR" >&2
    exit 1
}
echo "Depends (dpkg-shlibdeps): $DEPS"

SIZE=$(du -sk "$ROOT/usr" | cut -f1)
cat > "$ROOT/DEBIAN/control" <<CONTROL
Package: $PKG
Version: $VER
Section: editors
Priority: optional
Architecture: $DEB_ARCH
Installed-Size: $SIZE
Maintainer: Starling <dev@starling.build>
Depends: $DEPS
Recommends: fonts-noto-cjk, fonts-noto-color-emoji
Description: Starling Office — Writer, Sheets and Slides
 Word documents, Excel spreadsheets and PowerPoint presentations, opened
 and saved in their own formats (.docx, .xlsx, .pptx), as an ordinary
 window on GNOME, KDE and other desktops, Wayland or X11.
 .
 GPU-rendered; carries the fonts it lays documents out with.
CONTROL

dpkg-deb --build --root-owner-group "$ROOT" >/dev/null
ls -lh "$OUT"/${PKG}_${VER}_${DEB_ARCH}.deb
