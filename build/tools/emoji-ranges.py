#!/usr/bin/env python3
"""Prints the Swift range tables of RichLayout+Emoji.swift from emoji-data.txt (Unicode 16):
    emoji-ranges.py emoji-data.txt > apps/OfficeApp/Sources/OfficeText/RichLayout+Emoji.swift
(Emoji=Yes, not Emoji_Presentation, above ASCII: the characters U+FE0F turns to colour; Emoji_Presentation: the ones U+FE0E turns to outlines.)"""
import sys
P, E = set(), set()
for line in open(sys.argv[1], encoding="utf-8"):
    line = line.split("#")[0].strip()
    if not line: continue
    r, prop = [x.strip() for x in line.split(";")]
    a = r.split("..")
    rng = range(int(a[0], 16), int(a[-1], 16) + 1)
    if prop == "Emoji_Presentation": P.update(rng)
    elif prop == "Emoji": E.update(rng)
T = {c for c in E if c >= 0x80 and c not in P}
def ranges(s):
    s = sorted(s); out = []
    for c in s:
        if out and out[-1][1] == c - 1: out[-1][1] = c
        else: out.append([c, c])
    return ", ".join("0x%X...0x%X" % (a, b) if a != b else "0x%X...0x%X" % (a, a) for a, b in out)
print('''// Generated by build/tools/emoji-ranges.py from emoji-data.txt (Unicode 16): do not edit.
extension RichLayout {
    /// Emoji=Yes without Emoji_Presentation (U+2764, U+263A, U+2714, U+2600 ...): an outline until U+FE0F follows.
    static let emojiTextBases: [ClosedRange<UInt32>] = [%s]
    /// Emoji_Presentation=Yes (U+231A, U+2B50, U+1F600 ...): colour until U+FE0E follows.
    static let emojiPresentation: [ClosedRange<UInt32>] = [%s]
}''' % (ranges(T), ranges(P)))
