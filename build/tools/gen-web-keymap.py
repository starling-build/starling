#!/usr/bin/env python3
"""Writes web/host/keymap.js from the Flutter web engine's key tables.

    build/tools/gen-web-keymap.py [path/to/key_map.g.dart]

The tables map a DOM KeyboardEvent's `code` to Flutter's physical key id
(USB HID usage) and its `key` to the logical key id, with a third table for
the keys whose logical id depends on `location` (left/right modifiers, the
numpad). They are generated upstream from the same source the engine's
other embedders use, so the web host reports the keys every other host
reports. Re-run when the engine moves; the output is committed.
"""
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = Path(sys.argv[1]) if len(sys.argv) > 1 else (
    REPO / "engine/src/flutter/lib/web_ui/lib/src/engine/key_map.g.dart")
OUT = REPO / "web/host/keymap.js"

text = SOURCE.read_text()


def table(name):
    body = re.search(r"const Map<String, int> " + name + r" = <String, int>\{(.*?)\n\};", text, re.S)
    entries = re.findall(r"'([^']+)': (0x[0-9a-fA-F]+)", body.group(1))
    return entries


def location_table():
    body = re.search(r"const Map<String, List<int\?>> kWebLogicalLocationMap = <String, List<int\?>>\{(.*?)\n\};", text, re.S)
    out = []
    for key, values in re.findall(r"'([^']+)': <int\?>\[([^\]]*)\]", body.group(1)):
        # A trailing comma in the source leaves an empty last part.
        parts = [v.strip() for v in values.split(",") if v.strip()]
        out.append((key, [None if p == "null" else p for p in parts]))
    return out


def js_key(k):
    return "'" + k.replace("\\", "\\\\").replace("'", "\\'") + "'"


lines = [
    "// GENERATED by build/tools/gen-web-keymap.py from the Flutter web engine's",
    "// key_map.g.dart — do not edit. Logical ids are above 2^32, hence BigInt.",
    "",
    "export const PHYSICAL = new Map([",
]
for key, value in table("kWebToPhysicalKey"):
    lines.append(f"  [{js_key(key)}, {value}],")
lines += ["]);", "", "export const LOGICAL = new Map(["]
for key, value in table("kWebToLogicalKey"):
    lines.append(f"  [{js_key(key)}, {value}n],")
lines += ["]);", "", "// By KeyboardEvent.location: standard, left, right, numpad.", "export const LOGICAL_BY_LOCATION = new Map(["]
for key, values in location_table():
    vals = ", ".join("null" if v is None else v + "n" for v in values)
    lines.append(f"  [{js_key(key)}, [{vals}]],")
lines += ["]);", ""]
OUT.write_text("\n".join(lines))
print(f"wrote {OUT.relative_to(REPO)}: {len(table('kWebToPhysicalKey'))} physical, {len(table('kWebToLogicalKey'))} logical")
