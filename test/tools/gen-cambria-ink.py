#!/usr/bin/env python3
"""Generate CambriaMathInk.swift from the measured Cambria Math ink TSV (metrics only)."""
import sys
src, out = sys.argv[1], sys.argv[2]
rows = []
for l in open(src):
    if l.startswith('#') or not l.strip(): continue
    c, a, b, sa, sb = l.split()
    rows.append((int(c, 16), float(a), float(b), float(sa), float(sb)))
with open(out, 'w') as f:
    f.write("// Copyright the Starling authors\n// SPDX-License-Identifier: Apache-2.0\n\n")
    f.write("// Generated by test/tools/gen-cambria-ink.py from Cambria Math's glyph bounding boxes as Word for Windows\n// lays them out: yMin, yMax in ems, then the same for the first script-style (ssty) variant.\n")
    f.write("extension OfficeFonts {\n    static let cambriaMathInk: [UInt32: (Float, Float, Float, Float)] = [\n")
    for i in range(0, len(rows), 3):
        f.write("        " + ", ".join("0x%X: (%g, %g, %g, %g)" % r for r in rows[i:i+3]) + ",\n")
    f.write("    ]\n}\n")
