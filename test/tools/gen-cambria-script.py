#!/usr/bin/env python3
"""Generate CambriaMathScript.swift from the measured Cambria Math advance TSV (metrics only):
code -> (advance, first ssty variant advance, italic correction, ssty italic correction), in ems."""
import sys
src, out = sys.argv[1], sys.argv[2]
rows = []
for l in open(src):
    if l.startswith('#') or not l.strip(): continue
    c, a, sa, i, si = l.split()
    rows.append((int(c, 16), float(a), float(sa), float(i), float(si)))
with open(out, 'w') as f:
    f.write("// Copyright the Starling authors\n// SPDX-License-Identifier: Apache-2.0\n\n// Generated by test/tools/gen-cambria-script.py from Cambria Math's advances as Windows Office sets them (em): base, first script-style variant, then each one's MATH italic correction.\nextension OfficeFonts {\n    static let cambriaMathScript: [UInt32: (Float, Float, Float, Float)] = [\n")
    for i in range(0, len(rows), 3):
        f.write("        " + ", ".join("0x%X: (%g, %g, %g, %g)" % r for r in rows[i:i+3]) + ",\n")
    f.write("    ]\n}\n")
