"""Writes apps/OfficeApp/Sources/OfficeApp/Slides/PresetHandles.swift: the adjust handles (ahLst) of every
DrawingML preset, from ECMA-376's presetShapeDefinitions.xml as LibreOffice carries it
(oox/source/drawingml/customshapes/presetShapeDefinitions.xml).

    test/tools/gen-preset-handles.py presetShapeDefinitions.xml > apps/OfficeApp/Sources/OfficeApp/Slides/PresetHandles.swift

One string per preset, handles split by ';'. A handle is nine words:
    xy    gdRefX minX maxX gdRefY minY maxY posX posY
    polar gdRefR minR maxR gdRefAng minAng maxAng posX posY
with '-' where the definition has none."""
import sys
import xml.etree.ElementTree as ET

A = '{http://schemas.openxmlformats.org/drawingml/2006/main}'


def main(path):
    root = ET.parse(path).getroot()
    rows = []
    for shape in root:
        ah = shape.find(A + 'ahLst')
        if ah is None:
            continue
        handles = []
        for h in ah:
            pos = h.find(A + 'pos')
            kind = 'xy' if h.tag == A + 'ahXY' else 'polar'
            keys = (['gdRefX', 'minX', 'maxX', 'gdRefY', 'minY', 'maxY'] if kind == 'xy'
                    else ['gdRefR', 'minR', 'maxR', 'gdRefAng', 'minAng', 'maxAng'])
            words = [kind] + [h.get(k, '-') for k in keys] + [pos.get('x'), pos.get('y')]
            handles.append(' '.join(words))
        rows.append('        "%s": "%s",' % (shape.tag, ';'.join(handles)))
    print('// Copyright the Starling authors')
    print('// SPDX-License-Identifier: Apache-2.0')
    print()
    print('// The adjust handles (`ahLst`) of DrawingML\'s preset shapes (ECMA-376 Part 1, presetShapeDefinitions.xml,')
    print('// as LibreOffice carries it). Generated by test/tools/gen-preset-handles.py; not hand-edited.')
    print()
    print('enum PresetHandleTable {')
    print('    static let rows: [String: String] = [')
    print('\n'.join(rows))
    print('    ]')
    print('}')


if __name__ == '__main__':
    main(sys.argv[1])
