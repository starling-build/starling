#!/usr/bin/env python3
"""Writes OfficeText/UnderlineMetrics.swift: the underline and strikeout thickness (em) of
the faces documents name (from /data/corpus-cache/metrics/underline-*/underline-metrics.tsv,
metrics only) and of the bundled stand-in faces (post/OS2 tables of the files in
OfficeApp/Resources/fonts), so a run's rule can be scaled from the stand-in's to the named face's."""
import glob, struct, sys, os
tsv = sorted(glob.glob('/data/corpus-cache/metrics/underline-*/underline-metrics.tsv'))[-1]
def be(d, o, f): return struct.unpack_from('>' + f, d, o)
def tables(d):
    n = be(d, 4, 'H')[0]
    return {d[12+16*i:16+16*i].decode('latin1'): be(d, 20+16*i, 'II') for i in range(n)}
def names(d, t):
    o = t['name'][0]; cnt, so = be(d, o+2, 'HH'); out = {}
    for i in range(cnt):
        p, e, l, nid, ln, off = be(d, o+6+12*i, 'HHHHHH')
        if nid in (1, 2, 16, 17) and (p, e) in ((3, 1), (1, 0)):
            s = d[o+so+off:o+so+off+ln]
            out[nid] = s.decode('utf-16-be' if p == 3 else 'latin1')
    return out
run = []
for ln in open(tsv):
    if ln.startswith('#') or not ln.strip(): continue
    f = ln.rstrip('\n').split('\t')
    run.append((f[0].lower(), float(f[2]), float(f[4])))
stand = []
for p in sorted(glob.glob(os.path.join(os.path.dirname(__file__), '../../apps/OfficeApp/Sources/OfficeApp/Resources/fonts/*.ttf'))):
    d = open(p, 'rb').read(); t = tables(d)
    if 'post' not in t or 'OS/2' not in t or 'name' not in t: continue
    upm = be(d, t['head'][0]+18, 'H')[0]
    ut = be(d, t['post'][0]+10, 'h')[0] / upm
    st = be(d, t['OS/2'][0]+26, 'h')[0] / upm
    stand.append((os.path.basename(p)[:-4].lower(), ut, st))
out = ['// GENERATED by test/tools/gen-underline-metrics.py; metrics only (em).', 'enum UnderlineMetrics {',
       '    /// face name (lowercased, with its style) -> (underline thickness, strikeout size)',
       '    static let named: [String: (Double, Double)] = [']
out += [f'        "{n}": ({u:.4f}, {s:.4f}),' for n, u, s in run]
out += ['    ]', '    /// bundled stand-in file stem (lowercased) -> (underline thickness, strikeout size)', '    static let standIn: [String: (Double, Double)] = [']
out += [f'        "{n}": ({u:.4f}, {s:.4f}),' for n, u, s in stand]
out += ['    ]', '}']
open(os.path.join(os.path.dirname(__file__), '../../apps/OfficeApp/Sources/OfficeText/UnderlineMetrics.swift'), 'w').write('\n'.join(out) + '\n')
print(len(run), len(stand))
